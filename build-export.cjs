'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { CONTENT_TOKEN, serialize } = require('./export.js');

function buildTemplate(directory = __dirname) {
  let html = fs.readFileSync(path.join(directory, 'index.html'), 'utf8');
  const css = ['style.css', 'art-direction.css'].map(name => fs.readFileSync(path.join(directory, name), 'utf8')).join('\n');
  const app = fs.readFileSync(path.join(directory, 'app.js'), 'utf8');
  if (html.includes(CONTENT_TOKEN) || css.includes(CONTENT_TOKEN) || app.includes(CONTENT_TOKEN)) throw new Error('Reserved export token appears in source');
  if (/@import\b/i.test(css)) throw new Error('Export CSS must not contain @import dependencies');
  // Quoted URLs may contain parentheses (the inline SVG texture does).
  for (const match of css.matchAll(/url\(\s*(?:"([^"]*)"|'([^']*)'|([^)]*))\s*\)/gi)) {
    const url = (match[1] ?? match[2] ?? match[3]).trim();
    if (url && !/^(?:data:|#)/i.test(url)) throw new Error('Export CSS has an external dependency: ' + url);
  }
  if (/<\/style/i.test(css)) throw new Error('CSS contains an unsafe closing style tag');
  html = html.replace(/<script\b[^>]*>[\s\S]*?<\/script\s*>/gi, '');
  html = html.replace(/<link\b[^>]*>/gi, tag => {
    if (/\brel\s*=\s*["']stylesheet["']/i.test(tag) || /\bhref\s*=\s*["'][^"']*editor[^"']*["']/i.test(tag)) return '';
    return tag;
  });
  // Explicit marked editor markup is optional; normal app markup and SVG are preserved.
  html = html.replace(/<!--\s*EDITOR_START\s*-->[\s\S]*?<!--\s*EDITOR_END\s*-->/gi, '');
  if (!/<\/head\s*>/i.test(html) || !/<\/body\s*>/i.test(html)) throw new Error('index.html requires head and body closing tags');
  html = html.replace(/<\/head\s*>/i, () => '<style data-birthday-export>\n' + css + '\n</style>\n</head>');
  const scripts = '<script>window.BIRTHDAY_CONTENT = ' + CONTENT_TOKEN + ';</script>\n<script>\n' + app.replace(/<\/script/gi, '<\\/script') + '\n</script>\n';
  html = html.replace(/<\/body\s*>/i, () => scripts + '</body>');
  if (/<(?:script|img|audio|video|source|iframe)\b[^>]*\bsrc\s*=\s*["'](?!data:|#)[^"']+/i.test(html) || /<link\b[^>]*\bhref\s*=/i.test(html)) throw new Error('Page markup still contains an external resource; embed it before building');
  return { version: 1, html };
}
function build(directory = __dirname) {
  const template = buildTemplate(directory);
  const destination = path.join(directory, 'export-template.js');
  fs.writeFileSync(destination, '/* Generated by build-export.cjs; rebuild after page changes. */\nwindow.BIRTHDAY_EXPORT_TEMPLATE = ' + serialize(template) + ';\n', 'utf8');
  return destination;
}
if (require.main === module) console.log('Built ' + build());
module.exports = { buildTemplate, build };
